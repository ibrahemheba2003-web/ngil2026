export function curatedManhaj(sourceId: string): ManhajReport | null {
  return CURATED[sourceId] ?? null;
}

export function manhajSeedChunks(source: Source, focus?: string) {
  const query =
    focus?.trim() ||
    "منهج المفسر مولده وفاته الإسرائيليات العقيدة اللغة القراءات الأحكام قال أهل التأويل";
  return retrieveChunks(query, [source], 10);
}

export function reportToPlainText(report: ManhajReport): string {
  const lines = [
    `منهج المفسر — ${report.scholarName}`,
    "",
    `الاسم والنسب: ${report.nasab}`,
    `المولد: ${report.born} — ${report.birthplace}`,
    `الوفاة: ${report.died}`,
    `الاستقرار: ${report.residence}`,
    `الشيوخ: ${report.teachers}`,
    `التلاميذ: ${report.students}`,
    `المؤلفات: ${report.works}`,
    "",
  ];
  for (const section of report.sections) {
    lines.push(`## ${section.title}`, section.body, "");
    for (const q of section.quotes) {
      const vol = q.volume ? `ج${q.volume} ` : "";
      lines.push(`اقتباس (${vol}ص ${q.page}): «${q.excerpt}»`, "");
    }
  }
  lines.push(report.disclaimer);
  return lines.join("\n");
}
